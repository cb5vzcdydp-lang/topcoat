import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),{build}=createRequire(require.resolve('wrangler/package.json'))('esbuild');
await build({entryPoints:['lib/import-presets.ts','lib/exercise-swaps.ts'],outdir:'.test-output/new-roadmap',bundle:true,platform:'node',format:'esm',outExtension:{'.js':'.mjs'}});
const {importPresets,parsePresetHistory,presetMapping}=await import('../.test-output/new-roadmap/import-presets.mjs');
for(const preset of importPresets){
  const result=parsePresetHistory(preset.sample,preset.id);
  assert.ok(result.workouts.length+result.meals.length+result.daily.length>0);
  assert.equal(result.preset.id,preset.id);
  assert.throws(()=>parsePresetHistory('Wrong,Headers\n1,2',preset.id),/Missing columns/);
}
const hevy=importPresets[0],strong=importPresets[1],food=importPresets[2];
assert.equal(parsePresetHistory(hevy.sample,hevy.id).workouts[0].sets[0].weight,60);
assert.equal(parsePresetHistory(strong.sample,strong.id).workouts[0].sets[0].reps,8);
assert.equal(parsePresetHistory(food.sample,food.id).meals[0].fat,0,'a known zero is retained');
assert.equal(parsePresetHistory(importPresets[3].sample,importPresets[3].id).daily[0].calories,2100);
assert.throws(()=>parsePresetHistory(food.sample.replace(',90,8,12,0',',90,,12,0'),food.id),/Row 2: Missing number/);
assert.throws(()=>parsePresetHistory(food.sample.replace('2026-10-20','2026-02-31'),food.id),/Invalid date/);
assert.throws(()=>parsePresetHistory(hevy.sample.replace(',60,8',',60,8.5'),hevy.id),/whole repetition/);
assert.throws(()=>parsePresetHistory(hevy.sample,'bad'),/available import preset/);
assert.deepEqual(presetMapping(hevy,['START_TIME','exercise_title','reps','weight_kg']),{date:'START_TIME',exercise:'exercise_title',reps:'reps',weight:'weight_kg'});
const {suggestExerciseSwaps}=await import('../.test-output/new-roadmap/exercise-swaps.mjs');
const base={sets:2,min:6,max:12,muscle:'Chest',optional:false,gymPin:false,note:''};
const current={...base,id:'bench',name:'Barbell Bench Press',equipment:'free-weight'};
const dumbbell={...base,id:'db',name:'Dumbbell Bench Press',equipment:'free-weight',requiredEquipment:['Dumbbell','Bench']};
const machine={...base,id:'machine',name:'Machine Chest Press',equipment:'machine',requiredEquipment:['Chest Press Machine']};
const pushup={...base,id:'push',name:'Push Up',equipment:'bodyweight',requiredEquipment:[]};
const row={...base,id:'row',name:'Dumbbell Row',muscle:'Lats',equipment:'free-weight',requiredEquipment:['Dumbbell']};
const unknown={...base,id:'unknown',name:'Unknown press',equipment:'other',requiredEquipment:[]};
const candidates=[current,dumbbell,machine,pushup,row,unknown,dumbbell];
const picks=suggestExerciseSwaps(current,candidates,{availableEquipment:['Dumbbell','Bench']});
assert.deepEqual(new Set(picks.map(p=>p.exercise.id)),new Set(['db','push']));
assert.equal(suggestExerciseSwaps(current,candidates,{preferred:'Machine Chest Press'})[0].exercise.id,'machine');
assert.ok(!suggestExerciseSwaps(current,candidates,{preferred:'Machine Chest Press',availableEquipment:['Dumbbell','Bench']}).some(p=>p.exercise.id==='machine'));
assert.ok(!suggestExerciseSwaps(current,candidates,{selected:['db']}).some(p=>p.exercise.id==='db'));
assert.equal(suggestExerciseSwaps({...current,name:'Unclassified',muscle:'Other'},candidates).length,0);
assert.equal(suggestExerciseSwaps(current,candidates,{limit:1}).length,1);
assert.equal(suggestExerciseSwaps({...current,primaryMuscles:['Lats'],muscleOverride:true},candidates).length,0,'custom direct-muscle overrides affect suggestions');
assert.equal(current.name,'Barbell Bench Press');
console.log('PASS versioned provider layouts, column errors, row validation, true zero, units, daily summaries, equipment-aware swaps, preferred alternatives, exclusions, deduplication and no invented unknown-muscle matches');
