import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const r=createRequire(createRequire(import.meta.url).resolve('wrangler/package.json'));const {build}=r('esbuild');
await build({entryPoints:['lib/health-screenshot.ts'],outfile:'.test-output/health-screenshot.mjs',bundle:true,format:'esm',platform:'node'});
const {parseHealthScreenshotText}=await import('../.test-output/health-screenshot.mjs');
const rings=parseHealthScreenshotText('2026-10-20\nMove 612 kcal\nExercise 47 min\nStand 11 hrs\nSteps 12,438');
assert.deepEqual(rings,{steps:12438,active_calories:612,exercise_minutes:47,stand_hours:11,date:'2026-10-20'});
const sleep=parseHealthScreenshotText('Sleep summary\nTime Asleep 7 hr 36 min');
assert.equal(sleep.sleep_hours,7.6);
assert.equal(parseHealthScreenshotText('Daily summary\nTotal energy 2,487 kcal').total_calories,2487);
assert.deepEqual(parseHealthScreenshotText('A chart without exact values'),{});
console.log('health screenshot text extraction tests passed');
const split=parseHealthScreenshotText('Time Asleep\n7 hr 36 min\nMove\n612/500\nCAL\nTOTAL 2,487 CAL\nExercise\n47/30 MIN\nStand\n11/12 HRS\nSteps\n12,438');
assert.deepEqual(split,{sleep_hours:7.6,steps:12438,active_calories:612,total_calories:2487,exercise_minutes:47,stand_hours:11});
assert.equal(parseHealthScreenshotText('Move 120/500CAL').active_calories,120);
assert.equal(parseHealthScreenshotText('Active energy\n418.4 kJ').active_calories,100);
assert.equal(parseHealthScreenshotText('Time in bed 9 hr\nTime Asleep\n7 hr 20 min\nDeep\n1 hr 2 min').sleep_hours,7.33);
assert.deepEqual(parseHealthScreenshotText('2026-99-99\nMove\nExercise\nStand'),{});
const {screenshotHealthRows,emptyScreenshotValues}=await import('../.test-output/health-screenshot.mjs');
const vals={...emptyScreenshotValues('2026-10-20'),sleep_hours:7.6,total_calories:2487,steps:0};
const rows=screenshotHealthRows(vals,'client');assert.equal(rows.length,3);assert.equal(rows.find(r=>r.metric==='sleep_duration').value,7.6);assert.equal(rows.find(r=>r.metric==='steps').value,0);assert.deepEqual(screenshotHealthRows(vals,'client'),rows);
assert.throws(()=>screenshotHealthRows({...vals,sleep_hours:25},'client'),/Check/);
assert.throws(()=>screenshotHealthRows({...vals,date:'2026-02-30'},'client'),/valid date/);
assert.throws(()=>screenshotHealthRows(emptyScreenshotValues('2026-10-20'),'client'),/at least one/);
console.log('PASS split-line screenshots, ring numerator, kJ, sleep stages, zero values, validation and duplicate-safe health rows');
assert.equal(parseHealthScreenshotText('12,438 Steps').steps,12438);
