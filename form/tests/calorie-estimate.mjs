import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const r=createRequire(createRequire(import.meta.url).resolve('wrangler/package.json'));
const {build}=r('esbuild');
await build({entryPoints:['lib/calorie-estimate.ts'],outfile:'.test-output/calorie-estimate.mjs',bundle:true,format:'esm',platform:'node'});
const {estimateCaloriesAndMacros}=await import('../.test-output/calorie-estimate.mjs');
const normal=estimateCaloriesAndMacros({weightKg:74,weightToLoseKg:5,maintenanceKcal:2800,days:84});
assert.ok(normal);
assert.equal(normal.protein,98);
assert.equal(normal.fat,49);
assert.equal(normal.feasible,true);
assert.ok(normal.carbs>0);
assert.equal(normal.calories,2342);
const rushed=estimateCaloriesAndMacros({weightKg:74,weightToLoseKg:10,maintenanceKcal:5000,days:30});
assert.equal(rushed?.feasible,false);
assert.match(rushed?.reason||'',/above.*gradual planning pace/);
const noRoom=estimateCaloriesAndMacros({weightKg:50,weightToLoseKg:2,maintenanceKcal:1000,days:7});
assert.equal(noRoom?.feasible,false);
assert.match(noRoom?.reason||'',/no positive calorie target/);
assert.equal(estimateCaloriesAndMacros({weightKg:70,weightToLoseKg:70,maintenanceKcal:2000,days:100}),null);
assert.equal(estimateCaloriesAndMacros({weightKg:70,weightToLoseKg:2,maintenanceKcal:2000,days:0}),null);
console.log('Calorie/macro estimate assertions passed');
